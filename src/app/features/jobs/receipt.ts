import { Component, computed, inject, input, resource } from '@angular/core';
import { MatButtonModule } from '@angular/material/button';
import { MatIconModule } from '@angular/material/icon';
import { RouterLink } from '@angular/router';
import { Api } from '../../core/api';
import { METHOD_LABEL } from '../../core/reports';
import { Session } from '../../core/session';
import { EmptyState, Loading, PkDatePipe, PkrPipe } from '../../shared/ui';
import { Financials } from './financials';

/** Printable receipt / tax invoice. Uses the same access rules as the job itself. */
@Component({
  selector: 'app-receipt',
  imports: [
    RouterLink,
    MatButtonModule,
    MatIconModule,
    PkrPipe,
    PkDatePipe,
    Financials,
    Loading,
    EmptyState,
  ],
  template: `
    <div class="sheet-wrap">
      <div class="toolbar no-print">
        <a mat-button [routerLink]="back()"><mat-icon>arrow_back</mat-icon>Back to job</a>
        <button mat-flat-button type="button" (click)="print()">
          <mat-icon>print</mat-icon>Print or save as PDF
        </button>
      </div>
      @if (job.error()) {
        <app-empty
          icon="lock"
          title="Receipt unavailable"
          text="You don't have access to this receipt."
        />
      } @else if (!job.hasValue()) {
        <app-loading />
      } @else {
        @let v = job.value()!;
        <article class="sheet">
          <header>
            <div>
              <div class="brand">Repair Hub</div>
              <div class="muted small">Mobile repair and doorstep delivery · Pakistan</div>
            </div>
            <div class="right">
              <h1>Receipt</h1>
              <div class="mono">{{ v.invoice?.number ?? 'Not issued yet' }}</div>
              <div class="muted small">{{ v.invoice?.issuedAt | pkDate: 'date' }}</div>
            </div>
          </header>
          <section class="parties">
            <div>
              <h2>Billed to</h2>
              <p>
                {{ v.customer?.name }}<br />{{ v.job.deliveryAddress.line1 }},
                {{ v.job.deliveryAddress.city }}
              </p>
            </div>
            <div>
              <h2>Repaired by</h2>
              <p>{{ v.vendor?.shopName }}<br />{{ v.vendor?.areaName }}</p>
            </div>
            <div>
              <h2>Job</h2>
              <p class="mono">{{ v.job.ref }}</p>
              <p>{{ v.brand }} {{ v.model }}<br />{{ v.category }}</p>
            </div>
          </section>
          @if (quote(); as q) {
            <table class="data lines">
              <thead>
                <tr>
                  <th>Description</th>
                  <th class="num">Qty</th>
                  <th class="num">Unit</th>
                  <th class="num">Amount</th>
                </tr>
              </thead>
              <tbody>
                @for (i of q.items; track $index) {
                  <tr>
                    <td>{{ i.description }}</td>
                    <td class="num">{{ i.quantity }}</td>
                    <td class="num">{{ i.unitPrice | pkr }}</td>
                    <td class="num">{{ i.quantity * i.unitPrice | pkr }}</td>
                  </tr>
                }
              </tbody>
            </table>
          }
          <div class="totals"><app-financials [data]="v.financials" /></div>
          @if (v.transactions.length) {
            <h2>Payments</h2>
            <ul>
              @for (t of v.transactions; track t.id) {
                @if (t.status === 'CONFIRMED') {
                  <li>
                    {{ t.at | pkDate: 'date' }} ·
                    {{ t.kind === 'REFUND' ? 'Refund' : label[t.method] }} ·
                    {{ t.kind === 'REFUND' ? '−' : '' }}{{ t.amount | pkr }}
                  </li>
                }
              }
            </ul>
          }
          @if (v.warranty; as w) {
            <p class="small">
              <strong>Warranty:</strong> {{ w.days }} days, valid until
              {{ w.endsAt | pkDate: 'date' }}. {{ w.terms }}
            </p>
          }
          <footer class="muted small">
            All amounts in Pakistani rupees. Times are Pakistan Standard Time (UTC+5). This receipt
            was generated by the Repair Hub portfolio demo and is not a tax document.
          </footer>
        </article>
      }
    </div>
  `,
  styles: `
    :host {
      display: block;
      background: var(--mat-sys-surface-container-low);
      min-height: 100vh;
    }
    .sheet-wrap {
      max-width: 820px;
      margin: 0 auto;
      padding: 16px;
    }
    .toolbar {
      display: flex;
      justify-content: space-between;
      margin-bottom: 12px;
    }
    .sheet {
      background: var(--mat-sys-surface);
      border: 1px solid var(--mat-sys-outline-variant);
      border-radius: 12px;
      padding: 32px;
    }
    header {
      display: flex;
      justify-content: space-between;
      gap: 16px;
      border-bottom: 2px solid var(--mat-sys-primary);
      padding-bottom: 16px;
    }
    .brand {
      font: var(--mat-sys-headline-small);
      font-weight: 700;
      color: var(--mat-sys-primary);
    }
    .right {
      text-align: right;
    }
    h1 {
      margin: 0;
      font: var(--mat-sys-headline-small);
    }
    h2 {
      font: var(--mat-sys-label-large);
      color: var(--mat-sys-on-surface-variant);
      margin: 16px 0 4px;
      text-transform: uppercase;
      letter-spacing: 0.04em;
    }
    .parties {
      display: grid;
      grid-template-columns: repeat(3, 1fr);
      gap: 16px;
      p {
        margin: 0;
      }
    }
    .lines {
      margin: 24px 0 8px;
    }
    .totals {
      margin-left: auto;
      max-width: 340px;
    }
    footer {
      margin-top: 24px;
      border-top: 1px solid var(--mat-sys-outline-variant);
      padding-top: 12px;
    }
    @media (max-width: 599px) {
      .sheet {
        padding: 16px;
      }
      .parties {
        grid-template-columns: 1fr;
      }
    }
    @media print {
      :host {
        background: #fff;
      }
      .sheet {
        border: 0;
        padding: 0;
      }
    }
  `,
})
export class Receipt {
  private readonly api = inject(Api);
  private readonly session = inject(Session);
  readonly id = input.required<string>();
  protected readonly label = METHOD_LABEL;
  protected readonly job = resource({
    params: () => ({ id: this.id() }),
    loader: ({ params }) => this.api.query((b, t) => b.getJob(t, params.id)),
  });
  protected readonly quote = computed(() => {
    const v = this.job.value();
    return (
      v?.quotations.find((q) => q.id === v.invoice?.quotationId) ??
      v?.quotations.find((q) => q.status === 'APPROVED')
    );
  });
  protected readonly back = computed(() => {
    const base = {
      CUSTOMER: 'customer',
      VENDOR: 'vendor',
      AGENT: 'agent',
      STAFF: 'admin',
      SUPER_ADMIN: 'admin',
    }[this.session.role() ?? 'CUSTOMER'];
    return `/${base}/jobs/${this.id()}`;
  });

  protected print(): void {
    window.print();
  }
}
